import { z } from 'zod'

/**
 * WhatsApp message templates: the component model and the validation rules shared by the builder
 * UI and the API (docs/TEMPLATE_ENGINE.md → Components, Validation). The API and the web app
 * call the same `validateTemplate`, so they can never disagree about what is valid.
 */

export const TEMPLATE_CATEGORIES = ['MARKETING', 'UTILITY', 'AUTHENTICATION'] as const
export type TemplateCategory = (typeof TEMPLATE_CATEGORIES)[number]
export const TEMPLATE_STATUSES = [
  'DRAFT',
  'PENDING',
  'APPROVED',
  'REJECTED',
  'PAUSED',
  'DISABLED',
  'ARCHIVED',
] as const
export type TemplateStatus = (typeof TEMPLATE_STATUSES)[number]

export const TEMPLATE_LIMITS = {
  name: 512,
  headerText: 60,
  body: 1024,
  footer: 60,
  buttonText: 25,
  url: 2000,
  buttons: 10,
  urlButtons: 2,
  phoneButtons: 1,
  copyCodeButtons: 1,
  copyCodeExample: 15,
  /** Meta heuristic: at least this many words of text per body variable. */
  wordsPerVariable: 3,
} as const

/** Header media Meta accepts for template samples. */
export const TEMPLATE_HEADER_MEDIA = {
  IMAGE: { mime: /^image\/(jpeg|png)$/, max: 5 * 1024 * 1024, label: 'JPEG or PNG, up to 5 MB' },
  VIDEO: { mime: /^video\/mp4$/, max: 16 * 1024 * 1024, label: 'MP4, up to 16 MB' },
  DOCUMENT: { mime: /^application\/pdf$/, max: 100 * 1024 * 1024, label: 'PDF, up to 100 MB' },
} as const
export type HeaderMediaFormat = keyof typeof TEMPLATE_HEADER_MEDIA

/** Meta's fixed authentication body (the text is generated by Meta from these options). */
export const AUTH_BODY_TEXT = '{{1}} is your verification code.'

export const templateButtonSchema = z.discriminatedUnion('type', [
  z.object({ type: z.literal('QUICK_REPLY'), text: z.string() }),
  z.object({ type: z.literal('URL'), text: z.string(), url: z.string() }),
  z.object({ type: z.literal('PHONE_NUMBER'), text: z.string(), phoneE164: z.string() }),
  z.object({ type: z.literal('COPY_CODE'), example: z.string() }),
])
export type TemplateButton = z.infer<typeof templateButtonSchema>

export const templateComponentsSchema = z.object({
  header: z
    .discriminatedUnion('format', [
      z.object({ format: z.literal('TEXT'), text: z.string() }),
      z.object({
        format: z.enum(['IMAGE', 'VIDEO', 'DOCUMENT']),
        sampleFileId: z.uuid().nullable(),
      }),
    ])
    .optional(),
  body: z.object({ text: z.string() }),
  footer: z.object({ text: z.string() }).optional(),
  buttons: z.array(templateButtonSchema).max(20).optional(),
  /** AUTHENTICATION only: Meta's OTP options. */
  auth: z
    .object({
      securityRecommendation: z.boolean(),
      codeExpirationMinutes: z.number().int().min(1).max(90).nullable(),
    })
    .optional(),
})
export type TemplateComponents = z.infer<typeof templateComponentsSchema>

export const variableSamplesSchema = z.object({
  header: z.array(z.string()).max(1).optional(),
  body: z.array(z.string()).max(100),
  /** Keyed by button index (URL buttons with a `{{1}}` suffix). */
  buttons: z.record(z.string(), z.array(z.string()).max(1)).optional(),
})
export type VariableSamples = z.infer<typeof variableSamplesSchema>

export const templateDraftSchema = z.object({
  name: z.string().trim(),
  language: z.string().trim().min(2).max(15),
  category: z.enum(TEMPLATE_CATEGORIES),
  components: templateComponentsSchema,
  samples: variableSamplesSchema,
})
export type TemplateDraft = z.infer<typeof templateDraftSchema>

export const TEMPLATE_ISSUE_CODES = [
  'TEMPLATE_NAME_INVALID',
  'TEMPLATE_NAME_TAKEN',
  'TEMPLATE_VARIABLES_NOT_SEQUENTIAL',
  'TEMPLATE_VARIABLE_PLACEMENT',
  'TEMPLATE_TOO_MANY_VARIABLES',
  'TEMPLATE_SAMPLE_MISSING',
  'TEMPLATE_TOO_LONG',
  'TEMPLATE_BUTTONS_INVALID',
  'TEMPLATE_MEDIA_INVALID',
  'TEMPLATE_CATEGORY_MISMATCH',
  'TEMPLATE_BODY_REQUIRED',
  'TEMPLATE_AUTH_FORMAT',
] as const
export type TemplateIssueCode = (typeof TEMPLATE_ISSUE_CODES)[number]
export const templateIssueSchema = z.object({
  code: z.enum(TEMPLATE_ISSUE_CODES),
  path: z.string(),
  message: z.string(),
})
export type TemplateIssue = z.infer<typeof templateIssueSchema>
export const templateValidationSchema = z.object({
  valid: z.boolean(),
  errors: z.array(templateIssueSchema),
  warnings: z.array(templateIssueSchema),
})
export type TemplateValidation = z.infer<typeof templateValidationSchema>

const VARIABLE_RE = /\{\{\s*(\d+)\s*\}\}/g
/** Positional variable numbers in order of appearance, e.g. "Hi {{1}}, {{2}}" → [1, 2]. */
export function variablesIn(text: string): number[] {
  return [...text.matchAll(VARIABLE_RE)].map((m) => Number(m[1]))
}
/** Highest variable number (0 when none): how many samples/values the component needs. */
export const variableCount = (text: string | undefined): number =>
  text ? Math.max(0, ...variablesIn(text)) : 0
/** URL buttons may end with one `{{1}}`. */
export const urlVariableCount = (url: string): number => (/\{\{\s*1\s*\}\}$/.test(url) ? 1 : 0)

/** Replaces `{{n}}` with values (missing values keep the placeholder), for previews. */
export function renderTemplateText(text: string, values: readonly (string | undefined)[]): string {
  return text.replace(VARIABLE_RE, (whole, n: string) => values[Number(n) - 1] || whole)
}

const MARKETING_WORDS = [
  'offer',
  'discount',
  '% off',
  'sale',
  'promo',
  'coupon',
  'deal',
  'limited time',
  'buy now',
  'free gift',
]
const QUICK = 'QUICK_REPLY'
const E164 = /^\+[1-9]\d{7,14}$/

/** The shared validator (docs/TEMPLATE_ENGINE.md → Validation). Warnings never block. */
export function validateTemplate(draft: TemplateDraft): TemplateValidation {
  const errors: TemplateIssue[] = []
  const warnings: TemplateIssue[] = []
  const err = (code: TemplateIssueCode, path: string, message: string) =>
    errors.push({ code, path, message })
  const warn = (code: TemplateIssueCode, path: string, message: string) =>
    warnings.push({ code, path, message })
  const { components: c, samples } = draft

  if (!/^[a-z0-9_]+$/.test(draft.name) || draft.name.length > TEMPLATE_LIMITS.name)
    err(
      'TEMPLATE_NAME_INVALID',
      'name',
      'Use lowercase letters, numbers and underscores only (for example order_update).',
    )

  // Positional variables: {{1}}…{{n}} with no gaps, per component.
  const sequential = (text: string, path: string, max?: number) => {
    const vars = variablesIn(text)
    if (!vars.length) return
    const n = Math.max(...vars)
    const seen = new Set(vars)
    for (let i = 1; i <= n; i++)
      if (!seen.has(i)) {
        err(
          'TEMPLATE_VARIABLES_NOT_SEQUENTIAL',
          path,
          `Variables must be numbered {{1}} to {{${n}}} with no gaps ({{${i}}} is missing).`,
        )
        return
      }
    if (max !== undefined && n > max)
      err(
        'TEMPLATE_VARIABLES_NOT_SEQUENTIAL',
        path,
        `This part can have at most ${max} variable${max === 1 ? '' : 's'}.`,
      )
  }
  const sampleFor = (values: string[] | undefined, count: number, path: string) => {
    for (let i = 0; i < count; i++)
      if (!values?.[i]?.trim())
        err('TEMPLATE_SAMPLE_MISSING', `${path}.${i}`, `Add a sample value for {{${i + 1}}}.`)
  }

  if (draft.category === 'AUTHENTICATION') {
    // Meta's fixed OTP format: preset body, no header, one copy-code button.
    if (c.header)
      err('TEMPLATE_AUTH_FORMAT', 'components.header', 'Authentication templates have no header.')
    if (c.body.text !== AUTH_BODY_TEXT)
      err(
        'TEMPLATE_AUTH_FORMAT',
        'components.body.text',
        'Authentication templates use the fixed code message.',
      )
    if (c.buttons?.length !== 1 || c.buttons[0]?.type !== 'COPY_CODE')
      err(
        'TEMPLATE_AUTH_FORMAT',
        'components.buttons',
        'Authentication templates have exactly one copy-code button.',
      )
    if (!c.auth) err('TEMPLATE_AUTH_FORMAT', 'components.auth', 'Choose the code options.')
    sampleFor(samples.body, 1, 'samples.body')
    return { valid: errors.length === 0, errors, warnings }
  }
  if (c.auth)
    err(
      'TEMPLATE_AUTH_FORMAT',
      'components.auth',
      'Code options are for authentication templates only.',
    )

  // Header
  if (c.header?.format === 'TEXT') {
    if (!c.header.text.trim())
      err('TEMPLATE_TOO_LONG', 'components.header.text', 'Enter the header text.')
    if (c.header.text.length > TEMPLATE_LIMITS.headerText)
      err(
        'TEMPLATE_TOO_LONG',
        'components.header.text',
        `The header can be at most ${TEMPLATE_LIMITS.headerText} characters.`,
      )
    sequential(c.header.text, 'components.header.text', 1)
    sampleFor(samples.header, variableCount(c.header.text), 'samples.header')
  } else if (c.header && !c.header.sampleFileId) {
    err(
      'TEMPLATE_MEDIA_INVALID',
      'components.header.sampleFileId',
      'Upload a sample file for the header.',
    )
  }

  // Body
  const body = c.body.text
  if (!body.trim()) err('TEMPLATE_BODY_REQUIRED', 'components.body.text', 'Enter the message text.')
  if (body.length > TEMPLATE_LIMITS.body)
    err(
      'TEMPLATE_TOO_LONG',
      'components.body.text',
      `The message can be at most ${TEMPLATE_LIMITS.body} characters.`,
    )
  sequential(body, 'components.body.text')
  const trimmed = body.trim()
  if (/\}\}\s*\{\{/.test(body))
    err('TEMPLATE_VARIABLE_PLACEMENT', 'components.body.text', 'Put some text between variables.')
  if (trimmed.startsWith('{{') || trimmed.endsWith('}}'))
    err(
      'TEMPLATE_VARIABLE_PLACEMENT',
      'components.body.text',
      "The message can't start or end with a variable.",
    )
  const bodyVars = variableCount(body)
  sampleFor(samples.body, bodyVars, 'samples.body')
  if (bodyVars) {
    const words = body.replace(VARIABLE_RE, ' ').split(/\s+/).filter(Boolean).length
    if (words < bodyVars * TEMPLATE_LIMITS.wordsPerVariable)
      warn(
        'TEMPLATE_TOO_MANY_VARIABLES',
        'components.body.text',
        'Meta may reject messages with too many variables for their length. Add more text.',
      )
  }

  // Footer
  if (c.footer) {
    if (c.footer.text.length > TEMPLATE_LIMITS.footer)
      err(
        'TEMPLATE_TOO_LONG',
        'components.footer.text',
        `The footer can be at most ${TEMPLATE_LIMITS.footer} characters.`,
      )
    if (variablesIn(c.footer.text).length)
      err(
        'TEMPLATE_VARIABLE_PLACEMENT',
        'components.footer.text',
        "The footer can't contain variables.",
      )
  }

  // Buttons
  const buttons = c.buttons ?? []
  const buttonError = (message: string) =>
    err('TEMPLATE_BUTTONS_INVALID', 'components.buttons', message)
  if (buttons.length > TEMPLATE_LIMITS.buttons)
    buttonError(`Use at most ${TEMPLATE_LIMITS.buttons} buttons.`)
  const count = (t: TemplateButton['type']) => buttons.filter((b) => b.type === t).length
  if (count('URL') > TEMPLATE_LIMITS.urlButtons) buttonError('Use at most 2 website buttons.')
  if (count('PHONE_NUMBER') > TEMPLATE_LIMITS.phoneButtons)
    buttonError('Use at most 1 call button.')
  if (count('COPY_CODE') > TEMPLATE_LIMITS.copyCodeButtons)
    buttonError('Use at most 1 copy-code button.')
  // Quick replies and call-to-action buttons are grouped, never interleaved.
  const kinds = buttons.map((b) => (b.type === QUICK ? 'Q' : 'C')).join('')
  if (/Q+C+Q|C+Q+C/.test(kinds))
    buttonError('Keep quick replies together and call-to-action buttons together.')
  buttons.forEach((b, i) => {
    const path = `components.buttons.${i}`
    if (b.type !== 'COPY_CODE') {
      if (!b.text.trim()) err('TEMPLATE_BUTTONS_INVALID', `${path}.text`, 'Enter the button text.')
      if (b.text.length > TEMPLATE_LIMITS.buttonText)
        err(
          'TEMPLATE_TOO_LONG',
          `${path}.text`,
          `Button text can be at most ${TEMPLATE_LIMITS.buttonText} characters.`,
        )
    }
    if (b.type === 'URL') {
      const base = b.url.replace(/\{\{\s*1\s*\}\}$/, '')
      if (!/^https?:\/\/[^\s{}]+$/.test(base) || b.url.length > TEMPLATE_LIMITS.url)
        err(
          'TEMPLATE_BUTTONS_INVALID',
          `${path}.url`,
          'Enter a web address starting with https://. Only the end can be {{1}}.',
        )
      sampleFor(samples.buttons?.[String(i)], urlVariableCount(b.url), `samples.buttons.${i}`)
    }
    if (b.type === 'PHONE_NUMBER' && !E164.test(b.phoneE164))
      err(
        'TEMPLATE_BUTTONS_INVALID',
        `${path}.phoneE164`,
        'Enter the number in international format, for example +919876543210.',
      )
    if (
      b.type === 'COPY_CODE' &&
      (!b.example.trim() || b.example.length > TEMPLATE_LIMITS.copyCodeExample)
    )
      err(
        'TEMPLATE_BUTTONS_INVALID',
        `${path}.example`,
        'Enter an example code of up to 15 characters.',
      )
  })

  // Marketing wording in a UTILITY template: Meta may re-categorize it (warning only).
  if (draft.category === 'UTILITY') {
    const text =
      `${c.header?.format === 'TEXT' ? c.header.text : ''} ${body} ${c.footer?.text ?? ''}`.toLowerCase()
    const hit = MARKETING_WORDS.find((w) => text.includes(w))
    if (hit)
      warn(
        'TEMPLATE_CATEGORY_MISMATCH',
        'category',
        `"${hit}" sounds like marketing. Meta may change this template to the Marketing category.`,
      )
  }

  return { valid: errors.length === 0, errors, warnings }
}

/** Positional values a send needs, derived from the components. */
export function requiredVariables(components: TemplateComponents): {
  header: number
  body: number
  buttons: Record<string, number>
  headerMedia: HeaderMediaFormat | null
} {
  const buttons: Record<string, number> = {}
  ;(components.buttons ?? []).forEach((b, i) => {
    if (b.type === 'URL' && urlVariableCount(b.url)) buttons[String(i)] = 1
  })
  const header = components.header
  return {
    header: header?.format === 'TEXT' ? variableCount(header.text) : 0,
    body: variableCount(components.body.text),
    buttons,
    headerMedia: header && header.format !== 'TEXT' ? header.format : null,
  }
}

/** Values for a send (docs/TEMPLATE_ENGINE.md → Rendering and sending). */
export const templateVariablesSchema = z.object({
  header: z.array(z.string()).max(1).optional(),
  /** A READY file to use as the media header; the sample is used when omitted. */
  headerFileId: z.uuid().optional(),
  body: z.array(z.string()).max(100).default([]),
  buttons: z.record(z.string(), z.array(z.string()).max(1)).optional(),
})
export type TemplateVariables = z.infer<typeof templateVariablesSchema>

/** Every required value present and non-empty; returns the missing paths. */
export function missingVariables(
  components: TemplateComponents,
  values: TemplateVariables,
): string[] {
  const need = requiredVariables(components)
  const missing: string[] = []
  for (let i = 0; i < need.header; i++) if (!values.header?.[i]?.trim()) missing.push(`header.${i}`)
  for (let i = 0; i < need.body; i++) if (!values.body[i]?.trim()) missing.push(`body.${i}`)
  for (const [idx, n] of Object.entries(need.buttons))
    for (let i = 0; i < n; i++)
      if (!values.buttons?.[idx]?.[i]?.trim()) missing.push(`buttons.${idx}.${i}`)
  return missing
}
